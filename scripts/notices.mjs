#!/usr/bin/env node
/*
 * Writes THIRD_PARTY_NOTICES.md and public/third-party-notices.txt with the licence text of every
 * runtime dependency that ships inside the app (npm "dependencies" and their dependencies).
 */
import { readFileSync, existsSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

function pkgDir(name) {
  return join(root, 'node_modules', name);
}

function collect(name, seen) {
  if (seen.has(name) || !existsSync(pkgDir(name))) return;
  seen.add(name);
  const meta = JSON.parse(readFileSync(join(pkgDir(name), 'package.json'), 'utf8'));
  for (const dep of Object.keys(meta.dependencies ?? {})) collect(dep, seen);
}

const seen = new Set();
for (const dep of Object.keys(pkg.dependencies)) collect(dep, seen);
// The generated service worker bundles these Workbox modules.
for (const dep of ['workbox-precaching', 'workbox-routing', 'workbox-strategies'])
  collect(dep, seen);

const entries = [...seen].sort().map((name) => {
  const dir = pkgDir(name);
  const meta = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const file = readdirSync(dir).find((f) => /^(licen[sc]e|copying)(\.(md|txt))?$/i.test(f));
  const text = file ? readFileSync(join(dir, file), 'utf8').trim() : `License: ${meta.license}`;
  return { name, version: meta.version, license: meta.license, text };
});

const md = [
  '# Third-party notices',
  '',
  'Pandaro bundles the following open-source packages. Generated by `node scripts/notices.mjs`.',
  '',
  '| Package | Version | License |',
  '|---|---|---|',
  ...entries.map((e) => `| ${e.name} | ${e.version} | ${e.license} |`),
  '',
  ...entries.flatMap((e) => [`## ${e.name} ${e.version}`, '', '```text', e.text, '```', '']),
].join('\n');

writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), md);
writeFileSync(
  join(root, 'public', 'third-party-notices.txt'),
  entries
    .map((e) => `${e.name} ${e.version} (${e.license})\n\n${e.text}\n\n${'-'.repeat(72)}\n`)
    .join('\n'),
);
console.log(`Wrote notices for ${entries.length} packages`);
